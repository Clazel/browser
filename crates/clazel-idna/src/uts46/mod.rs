//! UTS #46 Unicode IDNA Compatibility Processing
//! (<https://www.unicode.org/reports/tr46/>), with the URL Standard's use
//! of it.
//!
//! - [`spec`]: a step-by-step transcription of UTS #46 §4, the Unicode
//!   Standard's Normalization Form C, RFC 5892's ContextJ rules, RFC 5893's
//!   Bidi rule and the URL Standard's IDNA section.
//! - [`contract`]: what the executable functions are proven to satisfy.
//! - [`nfc`] and [`process`]: the executable code, and its proofs.
//! - [`lemmas`]: facts proven about the spec; [`examples`]: WPT rows
//!   evaluated on the spec.
//! - [`tables`]: the shapes of the Unicode tables and their lookups;
//!   [`data`]: the tables, generated by `cargo xtask tables`.

pub mod contract;
pub mod data;
pub mod examples;
pub mod lemmas;
pub mod nfc;
pub mod process;
pub mod spec;
pub mod tables;
