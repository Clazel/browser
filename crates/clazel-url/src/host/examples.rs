//! The standard's examples, evaluated on the spec: the parse-serialize
//! table at the start of URL §3, the example after "find the IPv6 address
//! compressed piece index", and a few more inputs from the parsers' steps.
//!
//! This is a module of its own because Verus evaluates every `by
//! (compute_only)` assertion of a module it verifies, even with
//! `--verify-function`. A mutant that breaks an example would otherwise
//! fail every kill certificate placed next to it, not only the one about
//! the example.

#[allow(unused_imports)]
use super::spec::*;
#[allow(unused_imports)]
use vstd::prelude::*;

verus! {

/// The examples, evaluated.
pub proof fn lemma_examples() {
    // IPv4 parser on "0": 0 (serialized "0.0.0.0")
    assert(ipv4_parser(seq![0x30u32]) == Some(0nat)) by (compute_only);
    // IPv4 serializer on 0: "0.0.0.0"
    assert(ipv4_serializer(0) == seq![0x30u32, 0x2E, 0x30, 0x2E, 0x30, 0x2E, 0x30]) by (compute_only);
    // IPv4 parser on "0x": 0
    assert(ipv4_parser(seq![0x30u32, 0x78]) == Some(0nat)) by (compute_only);
    // IPv4 parser on "0xffffffff": 2^32 - 1
    assert(ipv4_parser(seq![0x30u32, 0x78, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66]) == Some(0xFFFF_FFFFnat)) by (compute_only);
    // IPv4 serializer on 2^32 - 1: "255.255.255.255"
    assert(ipv4_serializer(0xFFFF_FFFF) == seq![0x32u32, 0x35, 0x35, 0x2E, 0x32, 0x35, 0x35, 0x2E, 0x32, 0x35, 0x35, 0x2E, 0x32, 0x35, 0x35]) by (compute_only);
    // "09" ends in a number, and the IPv4 parser fails on it
    assert(ends_in_a_number(seq![0x30u32, 0x39]) && ipv4_parser(seq![0x30u32, 0x39]) is None) by (compute_only);
    // "example.255" ends in a number, and the IPv4 parser fails on it
    assert(ends_in_a_number(seq![0x65u32, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x2E, 0x32, 0x35, 0x35]) && ipv4_parser(seq![0x65u32, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x2E, 0x32, 0x35, 0x35]) is None) by (compute_only);
    // "example.com" does not end in a number
    assert(!ends_in_a_number(seq![0x65u32, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x2E, 0x63, 0x6F, 0x6D])) by (compute_only);
    // IPv6 parser on "0:0::1": ::1
    assert(ipv6_parser(seq![0x30u32, 0x3A, 0x30, 0x3A, 0x3A, 0x31]) == Some(seq![0nat, 0, 0, 0, 0, 0, 0, 1])) by (compute_only);
    // IPv6 serializer on ::1: "::1"
    assert(ipv6_serializer(seq![0nat, 0, 0, 0, 0, 0, 0, 1]) == seq![0x3Au32, 0x3A, 0x31]) by (compute_only);
    // "[0:0::1%5D" fails
    assert(host_parser(seq![0x5Bu32, 0x30, 0x3A, 0x30, 0x3A, 0x3A, 0x31, 0x25, 0x35, 0x44], false, |d: Seq<u32>, b: bool| None) is None) by (compute_only);
    // "[0:0::%31]" fails
    assert(host_parser(seq![0x5Bu32, 0x30, 0x3A, 0x30, 0x3A, 0x3A, 0x25, 0x33, 0x31, 0x5D], true, |d: Seq<u32>, b: bool| None) is None) by (compute_only);
    // opaque-host parser on "EXAMPLE.COM": "EXAMPLE.COM"
    assert(opaque_host_parser(seq![0x45u32, 0x58, 0x41, 0x4D, 0x50, 0x4C, 0x45, 0x2E, 0x43, 0x4F, 0x4D]) == Some(seq![0x45u32, 0x58, 0x41, 0x4D, 0x50, 0x4C, 0x45, 0x2E, 0x43, 0x4F, 0x4D])) by (compute_only);
    // opaque-host parser on "example%2Ecom": unchanged
    assert(opaque_host_parser(seq![0x65u32, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x25, 0x32, 0x45, 0x63, 0x6F, 0x6D]) == Some(seq![0x65u32, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x25, 0x32, 0x45, 0x63, 0x6F, 0x6D])) by (compute_only);
    // opaque-host parser on "faß.example": "fa%C3%9F.example"
    assert(opaque_host_parser(seq![0x66u32, 0x61, 0xDF, 0x2E, 0x65, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65]) == Some(seq![0x66u32, 0x61, 0x25, 0x43, 0x33, 0x25, 0x39, 0x46, 0x2E, 0x65, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65])) by (compute_only);
    // opaque-host parser on "example^example": failure
    assert(opaque_host_parser(seq![0x65u32, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x5E, 0x65, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65]) is None) by (compute_only);
    // In 0:f:0:0:f:f:0:0 the compressed piece index is the second 0 (index 2)
    assert(find_ipv6_compressed_piece_index(seq![0nat, 0xf, 0, 0, 0xf, 0xf, 0, 0]) == Some(2int)) by (compute_only);
    // IPv6 parser on "::ffff:1.2.3.4"
    assert(ipv6_parser(seq![0x3Au32, 0x3A, 0x66, 0x66, 0x66, 0x66, 0x3A, 0x31, 0x2E, 0x32, 0x2E, 0x33, 0x2E, 0x34]) == Some(seq![0nat, 0, 0, 0, 0, 0xffff, 0x0102, 0x0304])) by (compute_only);
    // IPv6 serializer on that: "::ffff:102:304"
    assert(ipv6_serializer(seq![0nat, 0, 0, 0, 0, 0xffff, 0x0102, 0x0304]) == seq![0x3Au32, 0x3A, 0x66, 0x66, 0x66, 0x66, 0x3A, 0x31, 0x30, 0x32, 0x3A, 0x33, 0x30, 0x34]) by (compute_only);
    // IPv6 parser on "1:2:3:4:5:6:7:8"
    assert(ipv6_parser(seq![0x31u32, 0x3A, 0x32, 0x3A, 0x33, 0x3A, 0x34, 0x3A, 0x35, 0x3A, 0x36, 0x3A, 0x37, 0x3A, 0x38]) == Some(seq![1nat, 2, 3, 4, 5, 6, 7, 8])) by (compute_only);
    // IPv6 parser on "1::"
    assert(ipv6_parser(seq![0x31u32, 0x3A, 0x3A]) == Some(seq![1nat, 0, 0, 0, 0, 0, 0, 0])) by (compute_only);
    // IPv6 parser on "::"
    assert(ipv6_parser(seq![0x3Au32, 0x3A]) == Some(seq![0nat, 0, 0, 0, 0, 0, 0, 0])) by (compute_only);
    // IPv6 serializer on 1:0:0:2:0:0:0:3: "1:0:0:2::3"
    assert(ipv6_serializer(seq![1nat, 0, 0, 2, 0, 0, 0, 3]) == seq![0x31u32, 0x3A, 0x30, 0x3A, 0x30, 0x3A, 0x32, 0x3A, 0x3A, 0x33]) by (compute_only);
    // IPv4 parser on "1.2.3": 1.2.0.3
    assert(ipv4_parser(seq![0x31u32, 0x2E, 0x32, 0x2E, 0x33]) == Some(0x0102_0003nat)) by (compute_only);
    // IPv4 parser on "0300.0x10.010.": the empty last part is dropped, and the three parts (octal, hex, octal) give 192.16.0.8
    assert(ipv4_parser(seq![0x30u32, 0x33, 0x30, 0x30, 0x2E, 0x30, 0x78, 0x31, 0x30, 0x2E, 0x30, 0x31, 0x30, 0x2E]) == Some(0xC010_0008nat)) by (compute_only);
    // IPv4 parser on "1.2.3.4.5": failure
    assert(ipv4_parser(seq![0x31u32, 0x2E, 0x32, 0x2E, 0x33, 0x2E, 0x34, 0x2E, 0x35]) is None) by (compute_only);
    // IPv4 parser on "256.0.0.1": failure
    assert(ipv4_parser(seq![0x32u32, 0x35, 0x36, 0x2E, 0x30, 0x2E, 0x30, 0x2E, 0x31]) is None) by (compute_only);
    // IPv4 parser on "1.2.3.256": failure
    assert(ipv4_parser(seq![0x31u32, 0x2E, 0x32, 0x2E, 0x33, 0x2E, 0x32, 0x35, 0x36]) is None) by (compute_only);
}

} // verus!
