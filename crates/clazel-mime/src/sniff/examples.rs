//! Real files from WPT, evaluated on the spec. `mimesniff/media/` serves
//! each with several Content-Types and expects it to play; MIME Sniffing
//! §6.2 is what must recognise it. These are the evidence for the WebM and
//! MP3-without-ID3 signatures, which `independent.rs` does not transcribe.
//! A prefix of each file is enough: every algorithm here decides within
//! it. The files are vendored in `tests/data/wpt-mimesniff/`
//! (`tests/conformance_sniffing.rs` runs the whole files through the exec
//! code).
//!
//! Kept in their own module: a mutation certificate is checked with its
//! module's other evaluations, so a mutant that changes an example would
//! otherwise stop the certificates (in `lemmas.rs`) that cite it.

